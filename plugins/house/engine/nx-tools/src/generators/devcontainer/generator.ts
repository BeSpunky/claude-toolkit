export default async function devcontainerGenerator(
  tree: Tree,
  options: DevcontainerSchema
): Promise<void> {
  if (!options.name) {
    throw new Error('devcontainer generator requires --name (the devcontainer / project name).');
  }
  // The image tag / Node feature version: the PROJECT's declared Node (.nvmrc) — never the machine running this.
  const nodeMajor = projectNodeMajor(tree);
  const voice = !!options.voice;
  const layers = activeLayers(tree, options.layers);
  const layerIds = layers.map((entry) => entry.id);

  const declared: Contributor[] = [...devcontainerFragments(tree, layers), ...(voice ? [{ id: 'voice', fragment: VOICE }] : [])];
  // The probe follows from the mounts: every workspace bind source it guarantees is one a contributor declared.
  const bindSources = workspaceBindSources(declared);
  const contributors: Contributor[] = bindSources.length ? [...declared, { id: 'host-probe', fragment: HOST_PROBE }] : declared;
  const houseComposition = compose(contributors, { nodeMajor });
  // An ADOPTED devcontainer that keeps an image of its own runs as THAT image's user: the house's mount targets
  // (`{{home}}/.claude`, …) must follow it, and no house `remoteUser` may be added to an image that may not have
  // that user at all — a container that cannot start is the worst thing an additive merge could produce.
  const imageSource = adoptedImageSource(tree, houseComposition.image.ref);
  const composition = imageSource.kind === 'build' ? houseComposition : compose(contributors, { nodeMajor, imageSource });
  const rendered = renderDevcontainerJson(options.name, layerIds, composition);

  // OWNERSHIP. The marker separates "regenerate the file we maintain" from "adopt somebody else's" — and it
  // records that as an EXPLICIT `owned` flag, not as its own existence.
  //
  // Deriving ownership from the marker merely EXISTING is a trap this fell into: the marker was written on
  // both paths, so the run after an adoption saw a marker, concluded it owned the file, and overwrote the
  // devcontainer it had carefully merged into the run before. The guarantee held for exactly one run — the
  // worst kind of bug, because a single-run test passes and the damage lands on somebody's second sync.
  //
  // A missing `owned` on an existing marker reads as NOT owned. That is the safe direction: the cost of
  // being wrong is an additive merge where a regeneration would have done (recoverable, visible in the
  // report below), against overwriting a file we don't own (not recoverable without the backup tag).
  const marker = readMarker(tree);
  const ours = marker?.owned === true;
  const exists = tree.exists(DEVCONTAINER);
  const owning = !exists || ours;

  // Whose postCreateCommand will the container actually run? Captured BEFORE the merge, because the merge
  // is additive: a project that declares none gets ours (so the house script runs), and a project that
  // declares its own keeps it (so the house script would not).
  const foreignPostCreate = exists ? postCreateCommandOf(tree) : undefined;

  // OWNERSHIP DECIDES WHETHER HOUSE KEYS ARE RE-ASSERTED — NEVER WHETHER THE PROJECT'S KEYS SURVIVE.
  //
  // Owning used to mean `tree.write(rendered)`: the whole file replaced, so anything the project had added
  // to a devcontainer we own — a forwarded port, a mount, an extension, and every comment explaining why —
  // was deleted on the next sync. That made the ownership marker a destructive binary, which in turn made
  // `claim-legacy-devcontainer-ownership` far more consequential than it looked: a migration that flipped a
  // flag was really arming a full rewrite of a file it had never read.
  //
  // Both paths now go through the same additive, comment-preserving merge. The only difference is what
  // happens on a key BOTH declare: an owned devcontainer takes the house value (that is what ownership
  // means), an adopted one keeps the project's. Keys the house does not know about survive in both.
  let skipped: string[] = [];
  let houseAdded: HouseWrite[] = [];
  if (!exists) {
    tree.write(DEVCONTAINER, rendered);
  } else {
    ({ skipped, houseAdded } = mergeIntoExisting(tree, rendered, ours ? 'assert' : 'adopt'));
  }
  if (imageSource.kind !== 'build') {
    // Recorded with the other keys the project kept: the house's `build` was NOT added beside its image source.
    skipped.push('build');
    logger.info(
      `[devcontainer] This devcontainer uses an image source of its own, so the house's cached package layer is not ` +
        `used: post-create installs the OS packages it lacks on every container create instead. ` +
        (imageSource.kind === 'house-ref'
          ? `Its image IS the house's (${composition.image.ref}), so switching is safe: replace "image" in ` +
            `${DEVCONTAINER} with "build": { "dockerfile": "${HOUSE_DOCKERFILE}", "context": "." } — the same image, ` +
            `the packages one cached layer.`
          : `Do NOT point it at .devcontainer/${HOUSE_DOCKERFILE}: that builds FROM the house's image, not yours. To ` +
            `cache the packages, install them in your own image's build instead.`),
    );
  }

  writeImageFiles(tree, composition);

  // The LOCAL feature — the thing that makes the house script run in a project whose devcontainer we do
  // not own. Written on BOTH paths (see the function), and after the merge, which is what may have just
  // added `./features/bespunky-house-setup` to a foreign `features` map.
  writeHouseSetupFeature(tree);

  // `invoked` — not merely `owning`. Writing `.devcontainer/post-create.sh` into a project whose
  // postCreateCommand points somewhere else produces a 300-line provisioning script that never runs and
  // never says so: the worst kind of output, because it LOOKS like the setup happened. So the house script
  // only takes that filename when something will actually call it.
  const invoked = owning || !foreignPostCreate || foreignPostCreate.includes('post-create.sh');
  writePostCreate(tree, renderPostCreate(layerIds, composition, claudePlugins(layers)), invoked, owning);

  if (bindSources.length) writeHostProbe(tree, bindSources, voice);

  // The ADOPTION REPORT. An adopted devcontainer diverges from the house spec on every key it already
  // declared, permanently and by design — the merge is additive and never argues with the project's own
  // choices. Until now the only trace of that was a log line that scrolled past, so the divergence grew
  // with nothing to see it. Recording the skipped keys makes it a fact a human (or the SessionStart hook)
  // can look at and decide about. It is a RECORD, never an input: the next run re-reads the files and
  // recomputes the whole thing, exactly as with the layer stamp.
  const record: Json = {
    generator: '@bespunky/nx-tools:devcontainer',
    owned: owning,
    // What this devcontainer was composed for — a RECORD (the next run re-detects), and the carrier of the
    // voice intent, which has nothing in the workspace to detect it by (layers/agent.ts reads it back).
    layers: layerIds,
    voice,
  };
  if (!owning) {
    record.adopted = {
      note:
        'This devcontainer.json was written by the project, not by this generator, so house settings are ' +
        'only ADDED, never changed. The keys below already had project values and were left alone — apply ' +
        'any of them by hand if you want the house behaviour. `houseAdded` is what the house ADDED here — the ' +
        'record that lets a later migration clean up after the house without guessing (an entry counts only ' +
        'while the file still holds it exactly; change or remove one and it is yours).',
      skipped,
      // The PROVENANCE record (generators/_utils/devcontainer-provenance.ts): earlier runs' additions the file
      // still holds, plus this run's. Unlike `skipped` it accumulates — an addition happens once, and the
      // run that made it is the only one that knows.
      houseAdded: reconcileHouseAdded(recordedHouseAdded(marker), houseAdded, tryParse(tree.read(DEVCONTAINER, 'utf8') ?? '')),
    };
  }
  tree.write(MARKER, `${JSON.stringify(record, null, 2)}\n`);
}

/**
 * What the container runs on (`ImageSource`), read from an ADOPTED devcontainer — `build` when the house owns the
 * file, there is none yet, or it already builds from the house Dockerfile (a HOUSE-marked one, under any spelling
 * of its path, or the legacy `dockerFile` key). Otherwise its own image source decides: `house-ref` when it names
 * the house's image; else `foreign`, running as its declared `remoteUser`, else `containerUser`, else `root` (what a
 * plain language image — python, golang, … — runs as), with a note, since that last one is an assumption about an
 * image this generator cannot inspect.
 */
function adoptedImageSource(tree: Tree, houseImage: string): ImageSource {
  if (!tree.exists(DEVCONTAINER) || readMarker(tree)?.owned === true) return { kind: 'build' };
  const existing = tryParse(tree.read(DEVCONTAINER, 'utf8') ?? '');
  if (!existing) return { kind: 'build' };
  if (buildsHouseDockerfile(tree, existing)) return { kind: 'build' };
  if (!['image', 'build', 'dockerFile', 'dockerComposeFile'].some((key) => key in existing)) return { kind: 'build' };
  if (existing.image === houseImage) return { kind: 'house-ref' };
  const declared = [existing.remoteUser, existing.containerUser].find((user) => typeof user === 'string');
  if (typeof declared === 'string') return { kind: 'foreign', runsAs: declared };
  logger.info(
    `[devcontainer] This devcontainer keeps its own image and declares no remoteUser/containerUser, so the house ` +
      `mounts assume it runs as root (e.g. the .claude mount targets /root/.claude). If the image runs as ` +
      `another user, declare "remoteUser" in ${DEVCONTAINER} and re-run the sync.`,
  );
  return { kind: 'foreign', runsAs: 'root' };
}

/** Does this devcontainer build from the HOUSE's Dockerfile — the path, however spelled, and a file the house wrote? */
function buildsHouseDockerfile(tree: Tree, existing: Json): boolean {
  const build = existing.build as Json | undefined;
  const named = (build && typeof build === 'object' ? build.dockerfile : undefined) ?? existing.dockerFile;
  if (typeof named !== 'string' || posix.normalize(named) !== HOUSE_DOCKERFILE) return false;
  return isHouseFile(tree, HOUSE_DOCKERFILE_PATH);
}

/** A path the house may write: nothing is there, or what is there says the house generated it. Never somebody else's. */
function isHouseFile(tree: Tree, path: string): boolean {
  return !tree.exists(path) || (tree.read(path, 'utf8') ?? '').includes(HOUSE_SCRIPT_MARKER);
}

const HOUSE_DOCKERFILE_PATH = `.devcontainer/${HOUSE_DOCKERFILE}`;
const OS_PACKAGES_SCRIPT = '.devcontainer/house.packages.sh';
const OS_PACKAGES_LIST = '.devcontainer/os-packages.txt';
const GITATTRIBUTES = '.devcontainer/.gitattributes';
/** LF in every checkout: a CRLF copy of a shell script dies in dash (`set: Illegal option -`) — the IMAGE BUILD fails. */
const LF_ONLY = ['*.sh text eol=lf', 'os-packages.txt text eol=lf'];

/** The project's own package list — SEEDED once (class C), never regenerated: it is the project's to fill. */
const OS_PACKAGES_STUB = `# This project's own OS (Debian) packages. THIS FILE IS YOURS — created once, never regenerated.
#
# Package NAMES only, one per line (or several, space-separated); \`#\` starts a comment — no versions (\`pkg=1.2\`),
# no architectures (\`pkg:amd64\`). They are installed with the house's when the container image is built
# (.devcontainer/house.Dockerfile) — one cached Docker layer, so a rebuild reinstalls nothing unless a list changed.
# A name apt cannot find FAILS the image build (loudly, rather than a container quietly missing a tool); a virtual
# name (one only "provided" by another package) is never seen as installed, so prefer the real package.
#
# Example:
# postgresql-client
`;

/**
 * The image's files beside devcontainer.json:
 *   house.packages.sh — the one installer (OWNED). Always: post-create runs it too, whatever the image.
 *   house.Dockerfile  — OWNED, written while it is or can safely become the image (build / house-ref); on a foreign
 *                       image it would build the WRONG base, so it is not offered — and a house-written one is removed.
 *   os-packages.txt   — the project's list, SEEDED once.
 * An owned path holding a file the house did not write is never overwritten: it is reported and left.
 * `.devcontainer/.gitattributes` gains the LF lines it lacks (its other lines are the project's).
 */
function writeImageFiles(tree: Tree, composition: Composition): void {
  const owned = (path: string, content: string, mode?: number) => {
    if (!isHouseFile(tree, path)) {
      logger.warn(`[devcontainer] ${path} exists and the house did not write it — left untouched. Rename it to let the house write its own.`);
      return;
    }
    tree.write(path, content, mode === undefined ? undefined : { mode });
  };
  // 0o755 so the shebang/mode rule holds in the output; it is invoked as `sh <path>`, so the mode is not load-bearing.
  owned(OS_PACKAGES_SCRIPT, renderOsPackagesScript(composition.osPackages), 0o755);
  if (composition.imageSource.kind === 'foreign') {
    if (tree.exists(HOUSE_DOCKERFILE_PATH) && isHouseFile(tree, HOUSE_DOCKERFILE_PATH)) tree.delete(HOUSE_DOCKERFILE_PATH);
  } else {
    owned(HOUSE_DOCKERFILE_PATH, renderHouseDockerfile(composition));
  }
  if (!tree.exists(OS_PACKAGES_LIST)) tree.write(OS_PACKAGES_LIST, OS_PACKAGES_STUB);

  const attributes = tree.exists(GITATTRIBUTES) ? (tree.read(GITATTRIBUTES, 'utf8') ?? '') : '';
  const lacking = LF_ONLY.filter((line) => !attributes.split('\n').some((have) => have.trim() === line));
  if (lacking.length) {
    const sep = attributes === '' || attributes.endsWith('\n') ? '' : '\n';
    const heading = attributes.includes('# BeSpunky house') ? '' : '# BeSpunky house — LF in every checkout: the image build runs these with /bin/sh, which a CRLF line breaks.\n';
    tree.write(GITATTRIBUTES, `${attributes}${sep}${heading}${lacking.join('\n')}\n`);
  }
}

interface Marker {
  owned?: boolean;
  adopted?: { houseAdded?: unknown };
}

/**
 * The project's own `postCreateCommand`, as a string, or `undefined` when it has none (or declares it as an
 * array/object form we shouldn't second-guess — treated as "it has one", which is the cautious direction).
 */
function postCreateCommandOf(tree: Tree): string | undefined {
  const parsed = tryParse(tree.read(DEVCONTAINER, 'utf8') ?? '');
  const value = parsed?.postCreateCommand;
  if (value === undefined) return undefined;
  return typeof value === 'string' ? value : JSON.stringify(value);
}

/** The ownership marker, or `null` when absent/unparseable (both of which mean "we don't own this"). */
function readMarker(tree: Tree): Marker | null {
  if (!tree.exists(MARKER)) return null;
  const parsed = tryParse(tree.read(MARKER, 'utf8') ?? '');
  return parsed ? (parsed as Marker) : null;
}

/**
 * The companion script — `.devcontainer/post-create.sh` — owns all multi-step setup so
 * devcontainer.json's postCreateCommand stays a one-liner. It is COMPOSED from the active layers' pieces
 * (`compose.ts` renderPostCreate), and each piece still self-adapts at run time where its trigger can change
 * between syncs (a declared @playwright/test, a host audio socket).
 *
 * TWO conditions must BOTH hold for the house script to take the canonical `post-create.sh` name, and
 * conflating them produced a silent failure each way round:
 *
 *   INVOKED — something will actually run it. Writing a 300-line provisioning script that the project's
 *             postCreateCommand never calls is the worst kind of output: it looks like setup happened.
 *   FREE    — no post-create.sh of somebody else's is already there. Overwriting one would delete their
 *             provisioning with no warning and no undo — worse than the devcontainer.json case, since a
 *             shell script's contents cannot be merged meaningfully.
 *
 * When either fails, the house script goes BESIDE the entry point and the one line needed to chain them is
 * printed for a human to place. Same "detect, don't execute" line the SessionStart hook holds: report the
 * fact, let the person who owns the file make the edit.
 */
function writePostCreate(tree: Tree, house: string, invoked: boolean, owning: boolean): void {
  const HOUSE_PATH = '.devcontainer/post-create.sh';
  const BESIDE_PATH = '.devcontainer/post-create.bespunky.sh';

  // "Free" means no one ELSE'S script is sitting at that path — which includes the case where the script
  // there is OURS from a previous run.
  //
  // Deriving that from `owning` alone was wrong, and wrong in a way that compounded: `owning` describes
  // devcontainer.json, so on an ADOPTED devcontainer it is permanently false, and the generator could never
  // recognise the post-create.sh it had itself written one run earlier. Result: run N wrote the house
  // script, run N+1 decided it was foreign and wrote a second copy beside it — manufacturing the very
  // duplication the beside-path exists to avoid, and re-manufacturing it on every sync thereafter.
  //
  // The script already announces its own provenance in its header, so ask IT rather than tracking more
  // state: a file we generated says so, a file somebody wrote by hand does not.
  const existingHouseScript = tree.exists(HOUSE_PATH) ? tree.read(HOUSE_PATH, 'utf8') ?? '' : '';
  const free = owning || !tree.exists(HOUSE_PATH) || existingHouseScript.includes(HOUSE_SCRIPT_MARKER);
  if (invoked && free) {
    tree.write(HOUSE_PATH, house);
    // A house script parked BESIDE on an earlier run (the project's postCreateCommand ran something else then) is
    // superseded now: left there, the chain feature would still run its stale body first, on every create.
    if (tree.exists(BESIDE_PATH) && (tree.read(BESIDE_PATH, 'utf8') ?? '').includes(HOUSE_SCRIPT_MARKER)) {
      tree.delete(BESIDE_PATH);
      logger.info(`[devcontainer] removed ${BESIDE_PATH} — the house setup now runs as ${HOUSE_PATH}, so the parked copy was superseded.`);
    }
    // The extension point's other half: create it ONCE so it is discoverable, and never touch it again.
    // An empty seam nobody knows about is not a seam.
    if (!tree.exists(LOCAL_PATH)) tree.write(LOCAL_PATH, LOCAL_STUB);
    return;
  }

  tree.write(BESIDE_PATH, house);
  logger.info(
    `[devcontainer] The house setup is in \`${BESIDE_PATH}\` rather than \`${HOUSE_PATH}\`, because ` +
      (free
        ? `this project's \`postCreateCommand\` runs something else, so a script at the usual name would never execute.`
        : `\`${HOUSE_PATH}\` already exists and this generator did not write it.`) +
      `\n    Chain it by adding this line to whatever your postCreateCommand does run:\n` +
      `    bash .devcontainer/post-create.bespunky.sh`
  );
}

