/**
 * The workspace-relative sources of every BIND mount the contributors declare (`source=${localWorkspaceFolder}/…`)
 * — what the probe must make exist. Read from the declared fragments, so a new layer's mount is covered by
 * declaring it, with nothing to keep in step. A source outside the workspace (`${localEnv:HOME}/…`) is the
 * host's own and not ours to create.
 */
function workspaceBindSources(contributors: readonly Contributor[]): string[] {
  const sources = contributors.flatMap(({ fragment }) =>
    (fragment.mounts ?? []).flatMap(({ mount }) => {
      if (!/(?:^|,)type=bind(?:,|$)/.test(mount)) return [];
      const source = /(?:^|,)source=\$\{localWorkspaceFolder\}\/([^,]+)/.exec(mount)?.[1];
      return source ? [source.replace(/\/+$/, '')] : [];
    }),
  );
  return [...new Set(sources)];
}

/**
 * The host probe — `.devcontainer/host-probe.sh`, run by devcontainer.json's `initializeCommand` on the host
 * before every container start. An OWNED template artifact: regenerated on every sync, on the owned and the
 * adopted path alike (the adopted merge adds the `initializeCommand` entry that calls it — see
 * `composeCommand`), because a gitignored bind source exists on a fresh clone only once the probe has run.
 * Rendered with the sources it guarantees and whether it bridges audio.
 *
 * Its audio output is a machine fact (this host's socket, or none), so `.devcontainer/.host/` is ignored —
 * committing it would hand one developer's symlink to every teammate's host.
 */
function writeHostProbe(tree: Tree, bindSources: readonly string[], audio: boolean): void {
  const rendered = readFileSync(join(__dirname, 'host-probe.sh.tpl'), 'utf8')
    .replace('{{bindSources}}', bindSources.map((source) => `'${source}'`).join(' '))
    .replace('{{audio}}', audio ? '1' : '0');
  // 0o755: the probe is invoked as `sh <path>`, so the mode is not load-bearing — it is set so a human can
  // run it directly when debugging, and so the shebang/mode checker's rule holds in the output.
  tree.write(HOST_PROBE_PATH, rendered, { mode: 0o755 });
  if (!audio) return;

  const gitignore = tree.exists('.gitignore') ? (tree.read('.gitignore', 'utf8') ?? '') : '';
  if (gitignore.includes(HOST_STATE_DIR)) return;
  const sep = gitignore === '' || gitignore.endsWith('\n') ? '' : '\n';
  tree.write(
    '.gitignore',
    `${gitignore}${sep}\n# Devcontainer host probe — this machine's audio-socket link (machine-local, never shared)\n${HOST_STATE_DIR}\n`
  );
}

/**
 * The one LOCAL devcontainer feature — `.devcontainer/features/bespunky-house-setup/`, referenced from
 * devcontainer.json by the relative id `./features/bespunky-house-setup`.
 *
 * IT INSTALLS NOTHING. Its entire content is a `postCreateCommand` that chains
 * `.devcontainer/post-create.bespunky.sh` when that file exists — and that is precisely the point.
 *
 * WHAT IT FIXES. `writePostCreate` above parks the house script at `post-create.bespunky.sh` whenever the
 * project's own `postCreateCommand` runs something else, and then prints the one line a human would have to
 * add to chain it. Until somebody does, ALL house provisioning — workspace deps, the Claude plugin
 * pre-install, the apt floor, Playwright, the Firebase JDK — silently never runs, in exactly the projects
 * this generator was built to retrofit. The script is written, looks provisioned, and executes never.
 *
 * WHY A FEATURE IS THE MECHANISM THAT CLOSES IT. Feature lifecycle commands are ADDITIVE: the spec has them
 * run BEFORE any command declared in devcontainer.json, never instead of it. So a `features` entry is the
 * one key whose value can *run* something without displacing what the project already runs — and the merge
 * above adds a missing `features` sub-key on the adopted path (`mergeIntoExisting(…, 'adopt')`), which is
 * how it reaches a devcontainer we do not own. Nothing else in this file can: every other house key is
 * either declarative or already spoken for by the project.
 *
 * WHY LOCAL RATHER THAN PUBLISHED. A `./`-prefixed feature is built from the folder beside devcontainer.json
 * — nothing published, nothing downloaded, no second version surface and no second deploy procedure. The
 * templates ship inside @bespunky/nx-tools and are versioned by it.
 *
 * UNCONDITIONAL, on the owned path and the adopted one alike. In an owned project the beside-path does not
 * exist and the chain command no-ops (harmless); in an adopted one it is the thing that makes house setup
 * run at all (essential). Being unconditional is also what removes a whole class of bug: there is no
 * retirement path, so the folder and the reference in devcontainer.json can never disagree — and this
 * generator never deletes a `.devcontainer/features/` folder it may not have written.
 */
function writeHouseSetupFeature(tree: Tree): void {
  // Same `__dirname` idiom as post-create.sh.tpl and the shared-browser generator: the scaffold copies the
  // whole nx-tools tree into node_modules and compiles the .ts → .js in place, so the .tpl files travel
  // beside the compiled generator and `__dirname` is the folder holding them. (`src/**/*.tpl` in the
  // package's `files` is a recursive glob, so the nested features/ templates are published too.)
  const template = (file: string) => join(__dirname, 'features', HOUSE_FEATURE, `${file}.tpl`);

  tree.write(
    `${HOUSE_FEATURE_DIR}/devcontainer-feature.json`,
    readFileSync(template('devcontainer-feature.json'), 'utf8')
  );

  // `install.sh` is the feature's own authorship decision, not this generator's: a feature whose whole
  // content is a lifecycle command may carry a trivial one or none at all. So it is copied IF the template
  // exists rather than assumed — this function's contract is "ship whatever the feature is made of".
  //
  // 0o755 is HYGIENE, not a requirement — and the distinction is worth stating because the opposite claim
  // was written here once and had to be retracted. The devcontainer CLI does not depend on the mode: the
  // build layer it generates runs `chmod -R 0755 <dest>` and the install wrapper runs `chmod +x
  // ./install.sh` before `./install.sh`, so a 0644 file builds fine. The bit is set anyway so the script
  // is directly runnable by a human doing hand-recovery, which is the only case that can observe it.
  // The .json needs no mode; it is only ever read.
  const install = template('install.sh');
  if (existsSync(install)) {
    tree.write(`${HOUSE_FEATURE_DIR}/install.sh`, readFileSync(install, 'utf8'), { mode: 0o755 });
  }
}

/**
 * ADDITIVE merge into a devcontainer.json this generator did not write.
 *
 * The rule is deliberately one-way: add what is missing, never change or remove what is there. A repo that
 * already has a devcontainer has already made choices — its base image, its Node version, its own
 * postCreateCommand — and those choices are almost always load-bearing for a project this generator knows
 * nothing about. Adding an extension it lacks is a courtesy; changing its image is a breakage.
 *
 * The cost is honest and worth naming: an adopted devcontainer does NOT get house updates to keys it
 * already defines. So the skipped keys are REPORTED rather than silently dropped — and returned, so the
 * caller can persist them. The reader can then apply any of them by hand, which is a decision they are
 * equipped to make and this generator is not.
 *
 * Returns the dotted paths that were left as the project had them, and what the house added (the provenance record).
 */
/**
 * Merge the rendered house devcontainer into the one on disk, in place, preserving comments.
 *
 * `mode` is the ONLY difference between owning a devcontainer and adopting one:
 *   - `'assert'` (we own it)  — a key both declare takes the HOUSE value.
 *   - `'adopt'`  (they own it) — a key both declare keeps the PROJECT's value, and is reported.
 *
 * Neither mode ever removes a key the house does not know about, and neither re-serializes the file — so
 * comments, including the ones between array members where people explain why a mount exists, survive both.
 */
function mergeIntoExisting(
  tree: Tree,
  rendered: string,
  mode: 'assert' | 'adopt',
): { skipped: string[]; houseAdded: HouseWrite[] } {
  const existingText = tree.read(DEVCONTAINER, 'utf8') ?? '{}';
  const existing = tryParse(existingText);
  const house = tryParse(rendered);

  if (!existing || !house) {
    logger.warn(
      `[devcontainer] \`${DEVCONTAINER}\` exists but could not be parsed as JSONC, so it was left exactly ` +
        `as-is. Fix or remove it and re-run to get the house devcontainer.`
    );
    return { skipped: [], houseAdded: [] };
  }

  const added: string[] = [];
  const skipped: string[] = [];
  const reasserted: string[] = [];
  const kept: string[] = [];
  // What the house ADDS, structured — the provenance record (see devcontainer-provenance.ts). Every addition
  // goes through `write` or `appendMissing`, so recording there misses none.
  const houseAdded: HouseWrite[] = [];
  let text = existingText;

  const write = (path: (string | number)[], value: unknown, bucket: string[]) => {
    if (isNoise(path, value)) return;
    text = applyEdits(text, modify(text, path, value, { formattingOptions: JSONC_FORMAT }));
    bucket.push(path.join('.'));
    if (bucket === added) houseAdded.push(...asRecorded(path.map(String), value));
  };

  const edit = (path: (string | number)[], value: unknown) => write(path, value, added);

  /**
   * Both sides declare this key with different values. In `assert` mode the house value wins (and the
   * project's own comment around it still survives — only the value is edited in place); in `adopt` mode
   * the project's stands and the divergence is recorded, permanently, in the marker.
   *
   * ONE EXCEPTION, and it belongs here rather than in `write`, because it is a statement about ASSERTING,
   * not about adding: when the HOUSE value is an empty container, there is nothing to assert. `{}` means
   * "this key, with default options" — it carries no information, so writing it over a project value that
   * has some can only ever DELETE information, never impose a house choice.
   *
   * The case that proved it: the feature spec permits the string shorthand, so a project may pin a version
   * on a house feature — `"ghcr.io/devcontainers/features/github-cli": "2.0.0"`. That is a deliberate
   * REFINEMENT of the house's `{}`, not a divergence from it, and it lands here at depth 2. Re-asserting
   * would flatten the pin back to `{}` on every sync while the comment explaining the pin survived
   * beside it — a silent downgrade of somebody's pinned toolchain, in a devcontainer we own.
   */
  const conflict = (path: (string | number)[], value: unknown) => {
    if (mode !== 'assert') {
      skipped.push(path.join('.'));
      return;
    }
    if (isEmptyContainer(value)) {
      kept.push(path.join('.'));
      return;
    }
    write(path, value, reasserted);
  };

  /**
   * Append missing array members ONE AT A TIME, in place.
   *
   * Replacing the whole array would re-serialize it — and take out every comment written BETWEEN its
   * members, which in a devcontainer.json is where people explain why a mount exists. jsonc-parser's
   * array insertion splices a single element at an index and leaves the rest of the text untouched.
   */
  const appendMissing = (path: (string | number)[], house: unknown[], current: unknown[]) => {
    const missing = house.filter((item) => !current.some((have) => sameMember(have, item)));
    let at = current.length;
    for (const item of missing) {
      text = applyEdits(
        text,
        modify(text, [...path, at], item, { formattingOptions: JSONC_FORMAT, isArrayInsertion: true })
      );
      added.push(`${path.join('.')}[+${JSON.stringify(item).slice(0, 40)}]`);
      houseAdded.push({ path: path.map(String), member: item });
      at++;
    }
  };

  for (const [key, value] of Object.entries(house)) {
    if (!(key in existing)) {
      edit([key], value);
      continue;
    }
    const composed = composeCommand(key, value, existing[key]);
    if (composed) {
      // The key now mixes the project's lifted command with the house entries — so the record names the house
      // ENTRIES, never the key: the whole key was never the house's to remove.
      write([key], composed, []);
      added.push(key);
      for (const [entry, entryValue] of Object.entries(value as Json)) houseAdded.push({ path: [key, entry], value: entryValue });
      continue;
    }
    // Present already — recurse one useful level into the containers where "missing sub-key" is the
    // common, safe case, and leave scalars strictly alone.
    if (isPlainObject(value) && isPlainObject(existing[key])) {
      mergeObject(key, value, existing[key] as Json, edit, appendMissing, conflict);
    } else if (Array.isArray(value) && Array.isArray(existing[key])) {
      appendMissing([key], value, existing[key] as unknown[]);
    } else if (!sameValue(value, existing[key])) {
      conflict([key], value);
    }
  }

  // Say what changed only when something did: a re-sync of a complete file writes nothing and claims nothing.
  if (text === existingText) return { skipped, houseAdded };
  tree.write(DEVCONTAINER, text);

  if (mode === 'assert') {
    logger.info(
      `[devcontainer] Updated the house-owned \`${DEVCONTAINER}\` in place.\n` +
        `  added:       ${added.length ? added.join(', ') : '(nothing — already complete)'}\n` +
        `  re-asserted: ${reasserted.length ? reasserted.join(', ') : '(nothing — already matching)'}\n` +
        (kept.length
          ? `  kept yours:  ${kept.join(', ')} (the house value there is empty — "with defaults" — so ` +
            `asserting it could only discard what you set, e.g. a feature version pin)\n`
          : '') +
        `  (keys this generator does not manage, and every comment, were left untouched)`
    );
  } else {
    logger.info(
      `[devcontainer] Adopted the existing \`${DEVCONTAINER}\` (not generator-written) — merged additively.\n` +
        `  added:      ${added.length ? added.join(', ') : '(nothing — already complete)'}\n` +
        `  left as-is: ${skipped.length ? skipped.join(', ') : '(nothing)'}\n` +
        `  (recorded in \`${MARKER}\` — this project keeps its own values for those keys)`
    );
  }

  return { skipped, houseAdded };
}

/**
 * A whole value the merge wrote, broken into record entries at the SAME granularity the merge itself works at
 * (`mergeIntoExisting` / `mergeObject`): a map's entries one level down (`features.<id>`, `remoteEnv.<name>`),
 * three levels for `customizations.vscode.*`, an array's members one by one. Recorded whole, the entry would
 * stop holding the moment the next run added a sibling — `features` written as one map is no longer that map
 * once a later layer adds a feature — and the provenance of everything in it would be pruned with it.
 */
function asRecorded(path: string[], value: unknown): HouseWrite[] {
  if (Array.isArray(value)) return value.map((member) => ({ path, member }));
  const depth = path[0] === 'customizations' ? 4 : 2;
  if (isPlainObject(value) && Object.keys(value).length && path.length < depth) {
    return Object.entries(value).flatMap(([key, inner]) => asRecorded([...path, key], inner));
  }
  return [{ path, value }];
}

/** Merge one nested object level: add absent keys, recurse into objects, union arrays, keep scalars. */
function mergeObject(
  prefix: string,
  house: Json,
  existing: Json,
  edit: (path: (string | number)[], value: unknown) => void,
  appendMissing: (path: (string | number)[], house: unknown[], current: unknown[]) => void,
  conflict: (path: (string | number)[], value: unknown) => void
): void {
  for (const [key, value] of Object.entries(house)) {
    const path = [prefix, key];
    if (!(key in existing)) {
      edit(path, value);
      continue;
    }
    if (isPlainObject(value) && isPlainObject(existing[key])) {
      // One more level covers customizations.vscode.{extensions,settings}, which is where the depth is.
      for (const [inner, innerValue] of Object.entries(value)) {
        const innerPath = [...path, inner];
        const have = (existing[key] as Json)[inner];
        if (have === undefined) edit(innerPath, innerValue);
        else if (Array.isArray(innerValue) && Array.isArray(have)) appendMissing(innerPath, innerValue, have);
        else if (isPlainObject(innerValue) && isPlainObject(have)) {
          for (const [leaf, leafValue] of Object.entries(innerValue)) {
            if (!(leaf in (have as Json))) edit([...innerPath, leaf], leafValue);
            else if (!sameValue(leafValue, (have as Json)[leaf])) conflict([...innerPath, leaf], leafValue);
          }
        } else if (!sameValue(innerValue, have)) conflict(innerPath, innerValue);
      }
      continue;
    }
    if (Array.isArray(value) && Array.isArray(existing[key])) {
      appendMissing(path, value, existing[key] as unknown[]);
      continue;
    }
    if (!sameValue(value, existing[key])) conflict(path, value);
  }
}

/**
 * Lifecycle commands the house declares in the spec's OBJECT form — named entries, run in parallel.
 *
 * Only `initializeCommand` (the host probe) today. `postCreateCommand` is deliberately NOT here: the house
 * reaches a foreign one through the local feature instead (see `writeHouseSetupFeature`), and its ordering
 * relative to the project's provisioning matters in a way the probe's does not.
 */
const COMPOSABLE_COMMANDS = new Set(['initializeCommand']);

/** The key a project's own string/array command is kept under once lifted into object form. */
const PROJECT_COMMAND_KEY = 'project';

/**
 * When the project already has a STRING or ARRAY form of a composable command, the house value can't be
 * added beside it — and BOTH ordinary outcomes are wrong:
 *   - adopt mode would keep theirs and report it. But a skipped probe is not a cosmetic divergence: the voice
 *     mount's source is the probe's output, so the container would refuse to START. A report nobody acts on
 *     in time is a broken container.
 *   - assert mode would write the house object over theirs, deleting a command we know nothing about.
 *
 * The spec's object form makes the dilemma false: `{ "project": <their command>, "bespunky-host-probe": … }`
 * runs exactly what they ran (a string still goes through a shell, an array still doesn't) AND the probe.
 * Lifting their value under its own key changes the SHAPE of the key, never what it does — so it is still
 * additive in the sense adoption promises (nothing of theirs is changed or lost), and it is the same move in
 * both modes. An existing OBJECT form needs none of this: the ordinary merge just adds the missing entry.
 *
 * Returns the composed value, or `undefined` when this key/shape isn't a composition case.
 */
function composeCommand(key: string, house: unknown, current: unknown): Json | undefined {
  if (!COMPOSABLE_COMMANDS.has(key) || !isPlainObject(house)) return undefined;
  if (typeof current !== 'string' && !Array.isArray(current)) return undefined;
  return { [PROJECT_COMMAND_KEY]: current, ...house };
}

/**
 * Do the project's value and the house value already AGREE?
 *
 * This is what makes the adoption report mean "where this project DIVERGES from the house" rather than the
 * far less useful "which keys happened to exist". Without it the report grew on the second run: keys the
 * FIRST run added were then present, so they were re-reported as left-as-is — listing settings that had in
 * fact been applied, which is precisely the confusion the report exists to remove. Structural equality,
 * since these are config values (scalars, small arrays and objects), not identities.
 */
function sameValue(a: unknown, b: unknown): boolean {
  return a === b || JSON.stringify(a) === JSON.stringify(b);
}

/**
 * The house keys whose CONTENTS are the information, so that rendering them empty means "nothing here" —
 * `"forwardPorts": []` in a repo that forwards nothing tells a reader less than the absent key did. These
 * are exactly the two keys this generator COMPUTES whole (from the layer flags) and can legitimately
 * render empty; adding them empty is noise, so it is suppressed.
 *
 * NAMED, rather than derived from the path's DEPTH — and the distinction is the bug. The guard used to
 * suppress EVERY empty container at every depth, which is exactly wrong for the other shape of container
 * in this file: a map whose KEYS are the information, where `{}` is a legitimate value meaning "with
 * defaults". A devcontainer feature is that shape — `"ghcr.io/…/github-cli": {}`,
 * `"./features/bespunky-house-setup": {}` — so in any project that already declared a `features` map, EVERY
 * house feature was silently dropped: the new local one, and `claude-code` and `github-cli` with it. The
 * one merge that has to work for an adopted devcontainer, skipped without a word.
 *
 * "Without a word" is why it went unnoticed for so long: the guard returned BEFORE `bucket.push`, so the
 * skip reached neither the log nor the adoption report — the report that exists precisely to make an
 * adopted devcontainer's divergence visible listed nothing, because nothing was even attempted.
 *
 * Depth cannot separate the two shapes and must not be used as a proxy for them: `portsAttributes` is a
 * map-of-options at depth 1, `features.<id>` is a map entry at depth 2. Only the key knows.
 */
const NOISE_WHEN_EMPTY = new Set(['forwardPorts', 'portsAttributes']);

/** Is writing `value` at `path` an addition that carries no information? (See `NOISE_WHEN_EMPTY`.) */
function isNoise(path: (string | number)[], value: unknown): boolean {
  return path.length === 1 && NOISE_WHEN_EMPTY.has(String(path[0])) && isEmptyContainer(value);
}

/** An empty array or empty object — something whose addition would carry no information. */
function isEmptyContainer(value: unknown): boolean {
  if (Array.isArray(value)) return value.length === 0;
  return isPlainObject(value) && Object.keys(value).length === 0;
}

/**
 * Are two array members "the same thing"? Exact equality for scalars; for a MOUNT string, equality of its
 * `target=` — because a mount that targets the same path is the same mount however its source is spelled,
 * and adding a second one for the same target is what breaks a container rather than enriching it.
 */
function sameMember(a: unknown, b: unknown): boolean {
  if (a === b) return true;
  if (typeof a === 'string' && typeof b === 'string') {
    const target = (s: string) => /(?:^|,)target=([^,]+)/.exec(s)?.[1];
    const ta = target(a);
    const tb = target(b);
    if (ta && tb) return ta === tb;
  }
  return JSON.stringify(a) === JSON.stringify(b);
}

const JSONC_FORMAT = { tabSize: 2, insertSpaces: true, eol: '\n' };

function tryParse(source: string): Json | undefined {
  try {
    const parsed: unknown = parseJson(source);
    return isPlainObject(parsed) ? parsed : undefined;
  } catch {
    return undefined;
  }
}

function isPlainObject(value: unknown): value is Json {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}
