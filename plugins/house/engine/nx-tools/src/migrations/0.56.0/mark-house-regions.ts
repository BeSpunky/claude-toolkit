// 0.56.0 — the files the house shares with a project get a HOUSE REGION, and a project's own half stops being rewritten.
//
// WHY A RUNG. Until 0.56.0 three files were wholly generator-owned and rewritten on every upgrade: the design system's
// `src/index.ts` barrel and its `STRUCTURE.md`, and every Angular app's `src/app/worktree-tab-label.ts`. Each sits where
// the project is told to extend it — the barrel is the design system's public API, STRUCTURE.md documents that design
// system, the tab label is app code the design-system rules tell a project to put on tokens — so every upgrade deleted
// a project's exports, docs and tokens (the report that opened this: `DsMotion` and `dsToken` gone from a barrel). The
// generators now rewrite only the region between `@bespunky/<name>:start` and `:end` (generators/_utils/house-region),
// and leave a file with no region alone, as the project's. Files already on disk carry no region, so without this rung a
// project would never get one, and the house could never again fix its own half.
//
// WHAT IT DOES, per file (a file that already carries its region is skipped):
//   1. STILL STOCK — the file is, modulo what a formatter changes, one of the shapes the house ever wrote there (every
//      revision of its template, frozen from git under ./house-regions/stock, each named by the earliest commit that shipped
//      it at its current path; and, where the workspace resolves prettier, each as that prettier formats it under the
//      file's own config, which is what every earlier run's formatFiles left on disk): nothing in it is the project's, so
//      it is replaced by the 0.56.0 shape (./house-regions/target, frozen here). A `{{token}}` of a stock shape matches
//      only its own grammar (a path, a name, the frozen pointer text), never free text — a token that could match
//      anything would let a project's own lines, written where a value sits, pass for stock and be rewritten away.
//   2. A BARREL that is not stock — its export statements that the house wrote, recognised one by one against every stock
//      barrel, move into the region, at the first one's place, each with the house comment directly above it (the region
//      carries its own copy); a stock header becomes the 0.56.0 header. Every other line stays where it is. Refused, and
//      reported, when the rest of the file still names anything the region exports (a project that edited a house
//      statement, re-exported a name another way, or wrapped it): the region would export it twice. A house export the
//      barrel had dropped comes back with the region, and is named in the report.
//   3. ANYTHING ELSE is the project's: it is left as it is, except for the header line that said the house rewrites it,
//      which is no longer true and is removed. Reported, with how to have the house maintain its part again.
import { type Tree, getProjects, logger } from '@nx/devkit';
import { readFileSync, readdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { basename, join } from 'node:path';
import { findDesignSystem } from '../../generators/_utils/design-system';
import { DAMAGED_REGION, findRegion, inLineEndingsOf, regionState, regionText } from '../../generators/_utils/house-region';
import { workspaceLinking } from '../../generators/_utils/linking';
import { workspaceIdentity } from '../../generators/_utils/workspace-identity';
import { toDnsLabel } from '../../generators/_utils/dns-label';
import { type PluginPointers, pluginPointerValues } from '../../generators/_utils/plugin-pointers';

const TAG = '[0.56.0 mark-house-regions]';
const HERE = join(__dirname, 'house-regions');

type Kind = 'angular-index' | 'neutral-index' | 'angular-structure' | 'neutral-structure' | 'tab-label';

/** A shared file: where it lives, which stock families it may be, the region it gets, and how it names itself in a report. */
interface Shared {
  readonly path: string;
  readonly kinds: readonly Kind[];
  readonly region: string;
  /** Values for the target's tokens a stock shape cannot supply. */
  readonly defaults: Record<string, string>;
}

/**
 * The one pointer a stock or target shape names, FROZEN as 0.56.0 renders it (generators/design-system/skill-pointers):
 * a stock STRUCTURE.md carries it, or nothing, where `{{designPhaseSkills}}` sits.
 */
const POINTERS: PluginPointers = {
  designPhaseSkills: ['bespunky-product-ux', ' (`bespunky-product-ux:stage-the-vision` → `realize-the-vision`)'],
};

/** The header lines that said the house rewrites the whole file — every variant shipped. */
const FALSE_HEADERS = [
  /^<!-- Generated by @bespunky\/nx-tools:design-system\. Rewritten on every run — do not hand-edit\. -->(?:\r?\n)?/m,
  /^\/\/ Generator-owned \(nx-tools (?:serve|worktree-tab-label) generator\) — do not edit by hand\.(?:\r?\n)?/m,
];

export default async function markHouseRegions(tree: Tree): Promise<void> {
  const prettier = workspacePrettier(tree);
  for (const shared of sharedFiles(tree)) await migrate(tree, shared, prettier);
}

function sharedFiles(tree: Tree): Shared[] {
  const files: Shared[] = [];
  const ds = findDesignSystem(tree);
  if (ds) {
    // The values the design-system generator renders with — what a stock shape's own text does not reliably supply.
    const defaults = {
      root: ds.root,
      name: basename(ds.root),
      specifier: `${basename(ds.root)}/styles`,
      importPath: workspaceLinking(tree).importPathOf(tree, ds.root) ?? `@${basename(ds.root)}`,
      tokenPrefix: 'ds',
      prefix: 'bs',
      ...pluginPointerValues(tree, POINTERS),
    };
    files.push({ path: `${ds.root}/src/index.ts`, kinds: ['angular-index', 'neutral-index'], region: 'design-system-api', defaults });
    files.push({ path: `${ds.root}/STRUCTURE.md`, kinds: ['angular-structure', 'neutral-structure'], region: 'design-system-structure', defaults });
  }
  const mainTreeSlug = toDnsLabel(workspaceIdentity(tree));
  for (const [, project] of getProjects(tree)) {
    const path = `${project.root}/src/app/worktree-tab-label.ts`;
    if (tree.exists(path)) files.push({ path, kinds: ['tab-label'], region: 'worktree-tab-label', defaults: { mainTreeSlug } });
  }
  return files;
}

async function migrate(tree: Tree, shared: Shared, prettier: Prettier | null): Promise<void> {
  const text = tree.read(shared.path, 'utf8');
  if (text === null) return;
  const state = regionState(text, shared.region);
  if (state === 'present') return;
  if (state === 'damaged') {
    logger.warn(`${TAG} ${DAMAGED_REGION(shared.path, [shared.region])}`);
    return;
  }

  for (const kind of shared.kinds) {
    for (const stock of await stockVariants(tree, kind, shared.path, prettier)) {
      const values = matchStock(text, stock);
      if (!values) continue;
      tree.write(shared.path, inLineEndingsOf(text, render(target(kind), { ...shared.defaults, ...values })));
      logger.info(`${TAG} ${shared.path}: still the house's stock text — rewritten with its house region (${shared.region}).`);
      return;
    }
  }

  if (shared.region === 'design-system-api' && moveHouseExports(tree, shared, text)) return;

  const kept = FALSE_HEADERS.reduce((next, header) => next.replace(header, ''), text);
  if (kept !== text) tree.write(shared.path, kept);
  logger.warn(
    `${TAG} ${shared.path}: changed by this project, so it is now wholly the project's — no upgrade will touch it again` +
      `${kept !== text ? ', and its "rewritten by the house" header line is removed' : ''}. For the house to keep its part ` +
      `current, put that part between \`@bespunky/${shared.region}:start\` and \`@bespunky/${shared.region}:end\` comment ` +
      `lines (or delete the file, re-run the upgrade and re-apply your changes outside the markers).`,
  );
}

/**
 * Case 2: move the house's own export statements into the region, leaving the project's where they are. False when there
 * is nothing to move or the move would export a name twice (reported by the caller's fallback).
 */
function moveHouseExports(tree: Tree, shared: Shared, original: string): boolean {
  const text = original.replace(/\r\n/g, '\n');
  const statements = [...text.matchAll(EXPORT_STATEMENT)];
  for (const kind of shared.kinds) {
    // Every house statement, flattened, with the house comments that ever sat directly above it (as stock text, so
    // its `{{tokens}}` match what they were filled with), and which of those comments was a whole stock header.
    const house = new Map<string, { comment: string; head: boolean }[]>();
    for (const stock of stockShapes(kind)) {
      [...stock.matchAll(EXPORT_STATEMENT)].forEach((m, i) => {
        const key = flatten(m[0]);
        if (!house.has(key)) house.set(key, []);
        house.get(key)!.push({ comment: stock.slice(commentAbove(stock, m.index!), m.index), head: i === 0 });
      });
    }
    const ours = statements.filter((m) => house.has(flatten(m[0])));
    if (ours.length === 0) continue;

    // What the move takes out: each statement, and the house comment directly above it when it is a stock one. A
    // stock header's values (the import path it names) are what the 0.56.0 header is filled with.
    const cuts: { from: number; to: number }[] = [];
    let headValues: Record<string, string> | null = null;
    for (const m of ours) {
      const above = commentAbove(text, m.index!);
      const comment = text.slice(above, m.index);
      const known = above < m.index! ? house.get(flatten(m[0]))!.find((c) => matchStock(comment, c.comment) !== null) : undefined;
      if (cuts.length === 0 && known?.head) headValues = matchStock(comment, known.comment);
      let to = m.index! + m[0].length;
      if (text[to] === '\n') to += 1;
      cuts.push({ from: known ? above : m.index!, to });
    }

    const rendered = render(target(kind), { ...shared.defaults, ...(headValues ?? {}) });
    const span = findRegion(rendered, shared.region)!;
    const region = rendered.slice(span.from, span.to);
    const exported = exportedNames(region);

    // The rest of the file must not name anything the region exports — in any form an export can take.
    let rest = '';
    let at = 0;
    for (const cut of cuts) {
      rest += text.slice(at, cut.from);
      at = cut.to;
    }
    rest += text.slice(at);
    const code = stripComments(rest);
    const clash = exported.find((name) => new RegExp(`(?<![\\w$])${name.replace(/\$/g, '\\$')}(?![\\w$])`).test(code));
    if (clash) {
      logger.warn(`${TAG} ${shared.path}: \`${clash}\` is still named outside the house's export statements (a statement this project changed, or its own export of it), so the house's exports were not moved into a region.`);
      return false;
    }

    // The region takes the first cut's place — under the 0.56.0 header when the cut carried the stock one.
    const lead = headValues ? rendered.slice(0, span.from) : '';
    let next = text.slice(0, cuts[0].from) + lead + region + '\n';
    at = cuts[0].to;
    for (const cut of cuts.slice(1)) {
      next += text.slice(at, cut.from);
      at = cut.to;
    }
    next += text.slice(at);
    next = next.replace(/\n{3,}/g, (run, offset: number) => (offset >= cuts[0].from ? '\n\n' : run)).replace(/\n*$/, '\n');
    tree.write(shared.path, inLineEndingsOf(original, next));

    const before = new Set(ours.flatMap((m) => exportedNames(m[0])));
    const returned = exported.filter((name) => !before.has(name));
    logger.info(
      `${TAG} ${shared.path}: the house's ${ours.length} export statement(s) moved into its house region (${shared.region}); ` +
        `the project's exports and comments are where they were.` +
        (returned.length ? ` The region also exports ${returned.map((n) => `\`${n}\``).join(', ')}, which this barrel had stopped exporting. If dropping them was deliberate, take the region over: delete its two marker lines and those exports with them.` : ''),
    );
    return true;
  }
  return false;
}

// A one-line `export { … } from '…'` (or wrapped over several lines), with an optional trailing line comment.
const EXPORT_STATEMENT = /^export\s*(?:type\s*)?\{[^}]*\}\s*from\s*['"][^'"]+['"]\s*;?[ \t]*(?:\/\/[^\n]*)?$/gm;

/** Where the run of `//` comment lines directly above the line starting at `index` begins (`index` when there is none). */
function commentAbove(text: string, index: number): number {
  let at = index;
  while (at > 0 && text[at - 1] === '\n') {
    const start = text.lastIndexOf('\n', at - 2) + 1;
    if (!/^[ \t]*\/\//.test(text.slice(start, at - 1))) break;
    at = start;
  }
  return at;
}

function stripComments(code: string): string {
  return code.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/\/\/[^\n]*/g, ' ');
}

function exportedNames(source: string): string[] {
  return [...source.matchAll(/export\s*(?:type\s*)?\{([^}]*)\}/g)].flatMap((m) =>
    m[1]
      .split(',')
      .map((entry) => entry.trim().replace(/^type\s+/, '').split(/\s+as\s+/).pop()!.trim())
      .filter(Boolean),
  );
}

const cache = new Map<string, string[]>();
function stockShapes(kind: Kind): string[] {
  if (!cache.has(kind)) {
    const dir = join(HERE, 'stock', kind);
    cache.set(kind, readdirSync(dir).sort().map((file) => readFileSync(join(dir, file), 'utf8')));
  }
  return cache.get(kind)!;
}

interface Prettier {
  format(source: string, options: Record<string, unknown>): string | Promise<string>;
  resolveConfig(path: string): Record<string, unknown> | null | Promise<Record<string, unknown> | null>;
}

/** The prettier the WORKSPACE resolves — the one every earlier run's formatFiles used — or null where there is none. */
function workspacePrettier(tree: Tree): Prettier | null {
  try {
    return createRequire(join(tree.root, 'package.json'))('prettier') as Prettier;
  } catch {
    return null;
  }
}

/** Every stock shape of `kind`, and each as the workspace's prettier formats it at `path` (tokens left in place). */
async function stockVariants(tree: Tree, kind: Kind, path: string, prettier: Prettier | null): Promise<string[]> {
  const raw = stockShapes(kind);
  if (!prettier) return raw;
  const filepath = join(tree.root, path);
  let config: Record<string, unknown> = {};
  try {
    config = (await prettier.resolveConfig(filepath)) ?? {};
  } catch {
    // An unreadable config: format with prettier's defaults, the next best guess at what is on disk.
  }
  const formatted: string[] = [];
  for (const stock of raw) {
    try {
      formatted.push(await prettier.format(stock, { ...config, filepath }));
    } catch {
      // A stock shape this prettier cannot parse: its raw form is still tried.
    }
  }
  return [...raw, ...formatted];
}

function target(kind: Kind): string {
  return readFileSync(join(HERE, 'target', `${kind}.tpl`), 'utf8');
}

function render(template: string, values: Record<string, string>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (match, token: string) => values[token] ?? match);
}

/**
 * What a formatter can change, folded away: whitespace, quote style, trailing commas, the length of a markdown table's
 * rule, `_` vs `*` emphasis, a void tag's self-closing slash, and where a rewrapped blockquote's `>` markers fall. Applied alike to the stock template and the file, so
 * it only ever widens a match.
 */
function flatten(text: string): string {
  return text
    .replace(/^[ \t]*>[ \t]?/gm, '')
    .replace(/"/g, "'")
    .replace(/\s+/g, '')
    .replace(/,([)\]}])/g, '$1')
    .replace(/-{3,}/g, '---')
    .replace(/_/g, '*')
    .replace(/\/>/g, '>');
}

const escapeRegExp = (text: string): string => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * What a `{{token}}` of a stock shape may stand for, flattened: a path, a package or a name — never free text, which
 * is what a project writes next to a value — and the pointer, which is exactly its frozen text or nothing.
 */
const TOKEN_GRAMMAR: Record<string, string> = {
  designPhaseSkills: `(?:${escapeRegExp(flatten(POINTERS.designPhaseSkills[1]))})?`,
};
const VALUE = '[A-Za-z0-9@/.*-]+?';

/** The token values when `text` is `stock` with its `{{tokens}}` filled, or null. A token's later uses must repeat its value. */
function matchStock(text: string, stock: string): Record<string, string> | null {
  const seen = new Set<string>();
  const pattern = flatten(stock)
    .split(/(\{\{\w+\}\})/)
    .map((part) => {
      const token = /^\{\{(\w+)\}\}$/.exec(part)?.[1];
      if (!token) return escapeRegExp(part);
      if (TOKEN_GRAMMAR[token]) return TOKEN_GRAMMAR[token];
      if (seen.has(token)) return `\\k<${token}>`;
      seen.add(token);
      return `(?<${token}>${VALUE})`;
    })
    .join('');
  const match = new RegExp(`^${pattern}$`, 's').exec(flatten(text));
  if (!match) return null;
  // The values were read out of FLATTENED text, so only a value flattening cannot have altered is kept; any other falls
  // back to the one the workspace gives. Inside the region the generator rewrites them right after, in any case.
  const values: Record<string, string> = {};
  for (const [token, value] of Object.entries(match.groups ?? {})) if (!value.includes('*')) values[token] = value;
  return values;
}
