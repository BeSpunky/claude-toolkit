#!/usr/bin/env bash
# BeSpunky devcontainer post-create.
#
# Runs ONCE after the container is built (or rebuilt). Owns all multi-step setup that doesn't fit cleanly as a
# devcontainer "feature" — the project's dependencies, the Claude Code plugin pre-install, the OS packages and
# whatever tooling this project's LAYERS bring.
#
# COMPOSED, not static: every section below was contributed by one of this project's layers (nx, agent, node), and a
# sync recomposes the whole file from the layers it detects. Add a layer (Firebase, a web app, …), re-run
# `scaffold.sh --sync`, rebuild — its steps appear here; a layer that leaves takes its steps with it.
#
# Generated by @bespunky/nx-tools:devcontainer. Edit the template in the toolkit,
# not this copy.
set -euo pipefail

# Devcontainer-cli runs postCreateCommand from the workspace root.
WS="$(pwd)"
# The user this container runs as, and its home — read, never assumed: the image decides them
# (`node` on typescript-node, `vscode` on the neutral devcontainers base).
ME="$(id -un)"
ME_GROUP="$(id -gn)"

# --- Reclaim Nx's volume mount points (nx) ---
# `.nx/cache` and `.nx/workspace-data` are named volumes, and Docker creates a fresh volume — and any mount
# point missing from the bind-mounted workspace, `.nx/` itself included on a fresh clone — owned by root. Nx
# runs as the remote user and would then hit EACCES on its first cache write. Guarded on ownership, so it is a
# no-op on every rebuild after the first.
for nx_dir in "$WS/.nx" "$WS/.nx/cache" "$WS/.nx/workspace-data"; do
  if [ -d "$nx_dir" ] && [ "$(stat -c %U "$nx_dir")" != "$ME" ]; then
    echo "[post-create] reclaiming ${nx_dir#"$WS"/} ownership for $ME"
    sudo chown "$ME:$ME_GROUP" "$nx_dir" || echo "[post-create] WARNING: could not reclaim ${nx_dir#"$WS"/} — Nx may fail to write its cache"
  fi
done

# --- The OS packages (one apt transaction, composed from this project's layers) ---
# Every active layer's packages, grouped BY CAPABILITY so a reader can tell why any given package is here —
# and so it leaves with the layer that needs it. Best-effort with retry: apt mirrors are occasionally flaky
# over Docker DNS, so a transient failure only WARNS — it never aborts post-create (set -e) and leaves the
# container half-provisioned.
#
# The list lives in ONE variable, so the hand-recovery command printed on failure is DERIVED from it rather
# than retyped. Accumulated across assignments rather than declared as a bash ARRAY so each capability keeps
# its own comment WITHOUT making the file bash-only: this script may be chained from a project's own `/bin/sh`
# postCreateCommand (`.devcontainer/post-create.bespunky.sh`), where an array is a PARSE error that kills the
# run at this line and skips every step below it.
OS_PACKAGES=""
# Durable shells. A tmux session outlives the client attached to it — the ONLY way an interactive shell
# opened into this container from the outside survives its opener restarting (the Docker Engine API cannot
# re-attach to an exec). No config is written on purpose: presence on PATH is the whole contract.
OS_PACKAGES="$OS_PACKAGES tmux"
# General utilities the house tooling shells out to.
OS_PACKAGES="$OS_PACKAGES curl"

echo "[post-create] installing OS packages:$OS_PACKAGES"
os_apt_ok=0
for attempt in 1 2 3; do
  # $OS_PACKAGES is deliberately UNQUOTED: word-splitting into one argument per package is the point. Safe
  # because every member is a Debian package name — no whitespace, no glob characters.
  # shellcheck disable=SC2086
  if sudo apt-get update && sudo apt-get install -y $OS_PACKAGES; then
    os_apt_ok=1; break
  fi
  if [ "$attempt" -lt 3 ]; then
    echo "[post-create] OS package install attempt $attempt/3 failed (often transient Docker DNS); retrying in $((attempt * 10))s..."
    sleep $((attempt * 10))
  fi
done
if [ "$os_apt_ok" = 1 ]; then
  # `apt-get install -y` exiting 0 IS the check; probing one member and announcing readiness for all of them
  # would be a false assurance.
  echo "[post-create] OS packages ready"
else
  echo "[post-create] WARNING: OS packages failed after 3 attempts — likely a transient network issue."
  echo "[post-create]          The container is otherwise ready, but EVERYTHING in this one transaction is missing."
  echo "[post-create]          Finish this one step once the network settles:"
  echo "[post-create]            sudo apt-get update && sudo apt-get install -y$OS_PACKAGES"
fi

# --- The Nx wrapper's installation (nx) ---
# A repo that hosts Nx through the wrapper (`./nx`, `.nx/nxw.js` — the house's choice for a repo with no
# package.json) keeps Nx, @nx/devkit and @bespunky/nx-tools in the GITIGNORED `.nx/installation`, pinned
# exactly in nx.json `installation`. Any `./nx` invocation installs it to match the pins; doing it HERE means
# the first `./nx g …` in the new container doesn't pay for it, and an offline rebuild says so now rather than
# mid-task. Self-adapting: a repo without the wrapper (Nx in node_modules) skips this — its package-manager
# install below brings Nx.
if [ -f "$WS/.nx/nxw.js" ] && [ -x "$WS/nx" ]; then
  echo "[post-create] installing the Nx wrapper's pinned packages (.nx/installation)"
  if "$WS/nx" --version > /dev/null; then
    echo "[post-create] Nx wrapper ready"
  else
    echo "[post-create] WARNING: the Nx wrapper could not install its packages (offline?). The next ./nx call retries."
  fi
fi

# --- The project's dependencies (node — this repo has a package.json) ---
# Which package manager does THIS project use? Detected at RUN time, not baked in at generation time: this
# script re-runs on every container rebuild, long after it was generated, and a project can change package
# manager in between.
#
# Getting this wrong is not cosmetic. `yarn install` in an npm project does not switch it, it writes a SECOND
# lockfile beside the first — after which `npm ci` fails for the whole team, caused by a container rebuild.
# THE DECLARATION FIRST, then the artifacts. `packageManager` is the only signal a human deliberately wrote;
# a lockfile is a by-product, and a STRAY one is exactly what an unconditional `yarn install` used to leave
# behind. The detection below is RENDERED from the one rule (generators/_utils/package-manager.ts), so it cannot
# disagree with the generators; scaffold.sh keeps the same order.
if [ -f "$WS/package.json" ]; then
  case "$(grep -m1 '"packageManager"' "$WS/package.json" 2>/dev/null | tr -d ' ')" in
    *'"pnpm@'*) PM=pnpm; PM_INSTALL="pnpm install"; PM_EXEC="pnpm exec" ;;
    *'"yarn@'*) PM=yarn; PM_INSTALL="yarn install"; PM_EXEC="yarn" ;;
    *'"npm@'*) PM=npm; PM_INSTALL="npm install"; PM_EXEC="npx --no-install" ;;
    *)
      if [ -f "$WS/pnpm-lock.yaml" ]; then PM=pnpm; PM_INSTALL="pnpm install"; PM_EXEC="pnpm exec"
      elif [ -f "$WS/yarn.lock" ]; then PM=yarn; PM_INSTALL="yarn install"; PM_EXEC="yarn"
      elif [ -f "$WS/package-lock.json" ]; then PM=npm; PM_INSTALL="npm install"; PM_EXEC="npx --no-install"
      else PM=yarn; PM_INSTALL="yarn install"; PM_EXEC="yarn"
      fi
      ;;
  esac
  echo "[post-create] package manager: $PM"
  echo "[post-create] $PM_INSTALL"
  $PM_INSTALL
else
  echo "[post-create] no package.json — no package-manager install (the Nx wrapper hosts the house tooling)"
fi

# --- Pre-install the Claude Code plugins at project scope (agent) ---
# So house skills/agents are live the moment the container opens. The list is the SAME one
# .claude/settings.json enables — both are composed from this project's layers — so the two can't drift. If
# the CLI isn't reachable (offline rebuild, etc.) we don't fail the build: .claude/settings.json declares the
# marketplaces, so Claude offers a one-click install on first session instead.
#
# THE claude-toolkit SOURCE SELF-ADAPTS. A repo that IS the claude-toolkit marketplace must register its OWN
# WORKING TREE, never the published copy of itself: the whole point of developing there is that a skill edit
# is live in the next session with no publish round-trip, and pulling the released plugins over the top would
# silently shadow the very files being edited. Narrow on purpose — the marketplace must be claude-toolkit
# ITSELF, not merely "some marketplace": a repo that is a DIFFERENT marketplace still wants the BeSpunky
# plugins from GitHub.
# One `<marketplace name> <source>` pair per line.
HOUSE_MARKETPLACES="nx-claude-plugins nrwl/nx-ai-agents-config
claude-toolkit BeSpunky/claude-toolkit"
HOUSE_PLUGINS="nx@nx-claude-plugins bespunky@claude-toolkit bespunky-project-starter@claude-toolkit bespunky-engineering@claude-toolkit bespunky-workflow@claude-toolkit bespunky-product-ux@claude-toolkit bespunky-vscode-identity@claude-toolkit bespunky-communication@claude-toolkit"
if grep -q '"name"[[:space:]]*:[[:space:]]*"claude-toolkit"' "$WS/.claude-plugin/marketplace.json" 2>/dev/null; then
  echo "[post-create] this repo IS the claude-toolkit marketplace — registering the working tree (dogfooding), not the published copy"
  TOOLKIT_SELF=1
else
  TOOLKIT_SELF=0
fi
echo "[post-create] pre-installing Claude Code plugins"
plugins_ok=1
while read -r mp_name mp_source; do
  [ -n "$mp_name" ] || continue
  if [ "$mp_name" = "claude-toolkit" ] && [ "$TOOLKIT_SELF" = 1 ]; then mp_source="$WS"; fi
  claude plugin marketplace add "$mp_source" || plugins_ok=0
done <<HOUSE_MARKETPLACES_EOF
$HOUSE_MARKETPLACES
HOUSE_MARKETPLACES_EOF
if [ "$plugins_ok" = 1 ]; then
  for plugin in $HOUSE_PLUGINS; do
    claude plugin install "$plugin" --scope project || { plugins_ok=0; break; }
  done
fi
if [ "$plugins_ok" = 1 ]; then
  echo "[post-create] Claude Code plugins installed at project scope"
else
  echo "[post-create] NOTE: Claude plugin pre-install skipped; .claude/settings.json will offer install on first run"
fi

# --- Voice prerequisites (the --voice intent; self-adapts on the host audio bridge) ---
# The bespunky-voice plugin speaks (TTS) and listens (STT) through a PulseAudio-protocol socket.
# Voice is OPT-IN (scaffold with --voice): only then does the devcontainer carry the host probe
# (initializeCommand) and the bind mount that lands the host's socket folder at ONE fixed
# endpoint, /run/bespunky/host/pulse/ — WSLg, native PulseAudio and PipeWire's pulse shim alike.
# On a host with no audio the probe mounts an empty dir instead, so the container still opens.
# So this step self-adapts on what actually ARRIVED: a socket in that folder means there is a
# speaker + mic to reach. When there is, install the free espeak-ng TTS floor (+ pulseaudio-utils
# for `paplay`) and pre-install the plugin, so `/voice` speaks the moment the container opens.
# Piper (the natural-voice upgrade) stays a manual, machine-local opt-in via the plugin's
# install-piper.sh — same stance as the claude-toolkit repo's own devcontainer. Best-effort +
# retry: a transient apt blip only warns, never aborts post-create (set -e) and leaves the
# container half-provisioned (same stance as every other best-effort step here).
# (`find -type s` rather than one fixed name: WSLg's own socket is called `PulseServer`, the
# others `native`. pactl isn't installed yet — this step installs it — so it can't be the probe.)
if [ -n "$(find /run/bespunky/host/pulse/ -maxdepth 1 -type s 2>/dev/null | head -n 1)" ]; then
  echo "[post-create] host audio socket detected (--voice) — provisioning bespunky-voice (espeak-ng + pulseaudio-utils)"
  voice_apt_ok=0
  for attempt in 1 2 3; do
    if sudo apt-get update && sudo apt-get install -y pulseaudio-utils espeak-ng; then
      voice_apt_ok=1; break
    fi
    if [ "$attempt" -lt 3 ]; then
      echo "[post-create] voice apt install attempt $attempt/3 failed (often transient Docker DNS); retrying in $((attempt * 10))s..."
      sleep $((attempt * 10))
    fi
  done
  if [ "$voice_apt_ok" = 1 ]; then
    echo "[post-create] voice engine ready (espeak-ng floor; run the plugin's install-piper.sh for the neural-voice upgrade)"
  else
    echo "[post-create] WARNING: voice engine install failed after 3 attempts — likely a transient network issue."
    echo "[post-create]          The container is otherwise ready; finish this one step once the network settles with:"
    echo "[post-create]            sudo apt-get update && sudo apt-get install -y pulseaudio-utils espeak-ng"
  fi
  # Pre-install the voice plugin at project scope so /voice is live on open. Best-effort:
  # the marketplace was added by the plugin pre-install; if that was offline, .claude/settings.json offers
  # install on first run. (The other house plugins are pre-installed by the plugin step;
  # bespunky-voice is gated here because without a host audio socket it can't play audio.)
  if claude plugin install bespunky-voice@claude-toolkit --scope project; then
    echo "[post-create] bespunky-voice plugin installed at project scope"
  else
    echo "[post-create] NOTE: bespunky-voice plugin install skipped (CLI offline?) — enable later with /plugin"
  fi
fi

# --- Project-specific setup (YOURS — this script's one extension point) ---
# Everything above is GENERATED and is overwritten on every `scaffold.sh --sync`. That is fine for
# house steps and fatal for yours: a project that needs its own provisioning (a database client, an
# internal CA, a language runtime the house image doesn't carry) had nowhere to put it but this file,
# where the next sync would silently delete it. Hence a seam.
#
# `.devcontainer/post-create.local.sh` is YOURS. It is created once, never regenerated, never read by
# any generator, and it runs last — after the workspace has deps, plugins and every house prerequisite,
# which is the only point at which project-specific setup can assume a working environment.
#
# Run in a SUBSHELL (bash, not source) so a stray `exit` or a variable named like one of ours can't
# reach back into this script. A failure WARNS rather than aborts — the same stance every step above
# takes, and for the same reason: a half-provisioned container is worse than a missing optional step.
if [ -f "$WS/.devcontainer/post-create.local.sh" ]; then
  echo "[post-create] running .devcontainer/post-create.local.sh (project-specific)"
  if bash "$WS/.devcontainer/post-create.local.sh"; then
    echo "[post-create] project-specific setup done"
  else
    echo "[post-create] WARNING: .devcontainer/post-create.local.sh exited non-zero — the house setup above completed,"
    echo "[post-create]          but your project-specific step did not. Re-run it directly to see the failure:"
    echo "[post-create]            bash .devcontainer/post-create.local.sh"
  fi
fi

echo "[post-create] done"
