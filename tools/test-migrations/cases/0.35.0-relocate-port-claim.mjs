// 0.35.0 — tools/shared-browser/port-claim(.test).mjs → tools/port-claim/.
//
// A move is a rename: the fixtures check the files arrive byte-identical (save the stamp and run line), the
// old ones are gone, every reference — including the house CLI a bare `nx migrate` leaves in place — points at
// the new home, a file without the house stamp is left alone, and another branch's worktree is never entered.
const STAMP = '// Generated by @bespunky/nx-tools:shared-browser. Edit the template in the toolkit, not this copy.';
const CLAIM = `#!/usr/bin/env node\n${STAMP}\nconsole.log('{}');\n`;
const TEST = `// Run:  node --test tools/shared-browser/\n${STAMP}\nimport './port-claim.mjs';\n`;
const SB_CLI = '#!/usr/bin/env bash\nPORT_CLAIM="$SCRIPT_DIR/port-claim.mjs"                    # host-port arbitration\n# see tools/shared-browser/port-claim.mjs\n';
const WD_CLI = '#!/usr/bin/env bash\n  local claim="$WORKSPACE_ROOT/tools/shared-browser/port-claim.mjs" out mine owner\n';

export default {
  name: '0.35.0 · relocate-port-claim',
  ladder: ['0.35.0/relocate-port-claim'],
  cases: [
    {
      name: 'the house copy moves and every reference follows',
      setup: (tree) => {
        tree.write('tools/shared-browser/port-claim.mjs', CLAIM);
        tree.write('tools/shared-browser/port-claim.test.mjs', TEST);
        tree.write('tools/shared-browser/shared-browser', SB_CLI);
        tree.write('tools/worktree-domains/worktree-domains', WD_CLI);
        tree.write('docs/ports.md', 'Run `node tools/shared-browser/port-claim.mjs list`.\n');
        tree.write('.claude/worktrees/other/tools/worktree-domains/worktree-domains', WD_CLI);
      },
      expect: (tree, t) => {
        t.missing('tools/shared-browser/port-claim.mjs');
        t.missing('tools/shared-browser/port-claim.test.mjs');
        t.has('tools/port-claim/port-claim.mjs', "console.log('{}');");
        t.has('tools/port-claim/port-claim.mjs', 'Generated by @bespunky/nx-tools:port-claim');
        t.has('tools/port-claim/port-claim.test.mjs', 'node --test tools/port-claim/');
        t.has('tools/shared-browser/shared-browser', 'PORT_CLAIM="$SCRIPT_DIR/../port-claim/port-claim.mjs"');
        t.has('tools/shared-browser/shared-browser', 'tools/port-claim/port-claim.mjs');
        t.has('tools/worktree-domains/worktree-domains', '$WORKSPACE_ROOT/tools/port-claim/port-claim.mjs');
        t.has('docs/ports.md', 'tools/port-claim/port-claim.mjs');
        t.has('.claude/worktrees/other/tools/worktree-domains/worktree-domains', 'tools/shared-browser/port-claim.mjs');
      },
    },
    {
      name: 'a port-claim.mjs without the house stamp is the project’s own — left in place',
      setup: (tree) => tree.write('tools/shared-browser/port-claim.mjs', '// mine\n'),
      expect: (tree, t) => {
        t.has('tools/shared-browser/port-claim.mjs', '// mine');
        t.missing('tools/port-claim/port-claim.mjs');
      },
    },
    {
      name: 'no shared browser at all: a no-op',
      setup: (tree) => tree.write('README.md', '# hi\n'),
      expect: (tree, t) => {
        t.missing('tools/port-claim/port-claim.mjs');
        t.has('README.md', '# hi');
      },
    },
  ],
};
